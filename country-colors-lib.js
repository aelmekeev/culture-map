export function getDistinctFlagColors(countryCodes) {
  const candidates = [];
  const uniqueColors = new Set();

  for (let code of countryCodes) {
    const colors = flagColors[code.toUpperCase()];
    if (!colors) {
      console.warn(`Country code not found in dataset: ${code}`);
      continue;
    }
    const colorChoices = colors.map(c => ({ hex: c.color, weight: c.weight }));
    candidates.push({ name: code.toUpperCase(), colors: colorChoices });
    for (const c of colorChoices) uniqueColors.add(c.hex);
  }

  // Precompute CIEDE2000 distances (it is mathematically heavy and very slow to calculate repeatedly)
  const distCache = {};
  const colorsArray = Array.from(uniqueColors);
  for (let i = 0; i < colorsArray.length; i++) {
      distCache[colorsArray[i]] = {};
      for (let j = 0; j < colorsArray.length; j++) {
          distCache[colorsArray[i]][colorsArray[j]] = chroma.deltaE(colorsArray[i], colorsArray[j]);
      }
  }

  // Precompute Lightness penalties
  const penaltyCache = {};
  for (const c of colorsArray) {
      const L = chroma(c).lab()[0];
      let p = 0;
      if (L > 95) p += 4000; // Heavy penalty for White
      if (L < 15) p += 200; // Moderate penalty for Black/Very dark
      penaltyCache[c] = p;
  }

  function getEnergy(assignment) {
    let totalEnergy = 0;
    for (let i = 0; i < assignment.length; i++) {
      for (let j = i + 1; j < assignment.length; j++) {
        const dist = distCache[assignment[i].color.hex][assignment[j].color.hex];
        if (dist < 20) {
          totalEnergy += (5000 / (dist + 0.1));
        } else {
          totalEnergy += (1000 / Math.pow(dist, 2));
        }
      }
    }
    for (let i = 0; i < assignment.length; i++) {
        totalEnergy += penaltyCache[assignment[i].color.hex];
        totalEnergy += ((1.0 - assignment[i].color.weight) * 500);
    }
    return totalEnergy;
  }

  let bestGlobalAssignment = null;
  let bestGlobalEnergy = Infinity;

  const RESTARTS = 200;
  for (let r = 0; r < RESTARTS; r++) {
    let currentAssignment = candidates.map(c => ({
      name: c.name,
      color: c.colors[Math.floor(Math.random() * c.colors.length)]
    }));

    let improved = true;
    while (improved) {
      improved = false;
      let currentEnergy = getEnergy(currentAssignment);
      
      let bestLocalChangeEnergy = currentEnergy;
      let bestLocalChange = null;

      for (let i = 0; i < currentAssignment.length; i++) {
        for (const testColor of candidates[i].colors) {
          if (testColor.hex === currentAssignment[i].color.hex) continue;
          
          const prevColor = currentAssignment[i].color;
          currentAssignment[i].color = testColor;
          
          const testEnergy = getEnergy(currentAssignment);
          
          if (testEnergy < bestLocalChangeEnergy) {
            bestLocalChangeEnergy = testEnergy;
            bestLocalChange = { index: i, newColor: testColor };
          }
          
          currentAssignment[i].color = prevColor; // revert
        }
      }

      if (bestLocalChange) {
        currentAssignment[bestLocalChange.index].color = bestLocalChange.newColor;
        improved = true;
      }
    }

    const finalEnergy = getEnergy(currentAssignment);
    if (finalEnergy < bestGlobalEnergy) {
      bestGlobalEnergy = finalEnergy;
      bestGlobalAssignment = currentAssignment.map(c => ({...c}));
    }
  }

  // Convert array back into a handy dictionary map for UI usage: { 'US': '#192f5d', ... }
  const colorMap = {};
  if (bestGlobalAssignment) {
      bestGlobalAssignment.forEach(item => {
          colorMap[item.name] = item.color.hex;
      });
  }

  return colorMap;
}
